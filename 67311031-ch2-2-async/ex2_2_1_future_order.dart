void main() {
  print("1. เริ่ม");
  Future.delayed(Duration(seconds: 3)).then((value) => print("2. โหลดเสร็จ"));
  print("3. จบ");
}

/*
Output:
1. เริ่ม
3. จบ
2. โหลดเสร็จ

เนื่องจาก print("1. เริ่ม") ทำงานบรรทัดแรก จึงออกมาเป็นผลลัพธ์บรรทัดแรก แล้วบรรทัดต่อมาเป็น Future 
ซึ่ง delay 3 วินาที ทำให้ print("3. จบ") ทำงานก่อน แล้วจึงค่อย print("2. โหลดเสร็จ")
 */